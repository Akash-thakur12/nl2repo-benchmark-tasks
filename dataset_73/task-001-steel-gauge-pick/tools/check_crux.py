#!/usr/bin/env python3
"""Prove the cruxes bite, rather than asserting that they do.

Each entry below is a complete, working, internally coherent selector that a
competent engineer could plausibly write after reading `instruction.md` and
skimming `environment/`. Each one takes exactly one wrong turn:

  B  it walks `data/w_shapes.csv` in the order the file happens to be in and
     returns the first acceptable row, because the schedule *looks* ordered.
     Or it breaks the 26.0 plf tie toward the deeper, stiffer member as the
     "conservative" choice.

  H  it computes one uniform load, one required Sx and one required Ix, then
     scans - the compute-once-then-scan shape the retired spreadsheet used.
     Variants: self-weight omitted from the dead load, L/360 applied to the
     total load instead of the live load alone, the L/240 total-load check
     dropped.

  C  it keeps the `SIGMA = 24_000.0` that ships in `environment/engine/engine.py`
     and applies it to every shape, ignoring `Lc_ft` / `Lu_ft` - the reading the
     stub constants, `docs/legacy_calc.md` and the retired header comments all
     endorse.

  I  it fits the whole of `data/legacy_picks.csv` instead of only the rows
     recorded under the revision in force, and so reimplements the superseded
     Revision A method.

For each one this runs the full behaviour suite and asserts that it fails, and
reports how many of the recorded picks it reproduces under each revision. A
variant that passed the suite would mean the tests do not actually depend on
that decision.

This script ships as evidence for the buyer. It contains no secrets: every
number in it is already in `environment/data/w_shapes.csv` or
`environment/docs/design_standard.md`.

Usage:  python tools/check_crux.py
"""
import csv
import os
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
TASK = HERE.parent
REFERENCE = TASK / "solution" / "engine"
TESTS = TASK / "tests" / "test_outputs.py"
PICKS = TASK / "environment" / "data" / "legacy_picks.csv"


# --------------------------------------------------------------------------
# A single naive selector, parameterised by the wrong turn it takes.
# --------------------------------------------------------------------------

TEMPLATE = '''
"""A plausible-but-wrong W-shape selector, generated by tools/check_crux.py."""
import numbers


class ValidationError(Exception):
    pass


class NotFoundError(Exception):
    pass


# (designation, weight_plf, Sx, Ix, Lc_ft, Lu_ft) in data/w_shapes.csv order.
SHAPES = [
    ("W4x13", 13.0, 5.46, 11.3, 4.3, 15.6),
    ("W6x9", 9.0, 6.20, 16.0, 4.2, 6.7),
    ("W6x12", 12.0, 7.30, 22.0, 4.2, 8.6),
    ("W6x16", 16.0, 9.50, 32.0, 4.3, 12.0),
    ("W8x10", 10.0, 8.50, 30.0, 4.2, 4.7),
    ("W8x13", 13.0, 9.70, 39.0, 4.2, 6.4),
    ("W8x15", 15.0, 11.30, 48.0, 4.2, 7.2),
    ("W8x18", 18.0, 13.40, 61.0, 5.2, 9.9),
    ("W10x12", 12.0, 10.30, 53.0, 3.9, 4.3),
    ("W10x15", 15.0, 12.00, 68.0, 4.2, 4.9),
    ("W10x17", 17.0, 13.50, 81.0, 4.2, 6.1),
    ("W10x19", 19.0, 15.00, 96.0, 4.2, 7.2),
    ("W12x14", 14.0, 12.00, 88.0, 3.5, 4.2),
    ("W12x16", 16.0, 13.40, 103.0, 4.1, 4.3),
    ("W12x19", 19.0, 15.40, 130.0, 4.2, 5.3),
    ("W12x22", 22.0, 17.40, 156.0, 4.3, 6.4),
    ("W14x22", 22.0, 18.20, 199.0, 5.3, 5.6),
    ("W14x26", 26.0, 21.40, 245.0, 5.3, 7.0),
    ("W16x26", 26.0, 24.10, 301.0, 5.6, 6.0),
    ("W18x35", 35.0, 33.20, 510.0, 6.0, 6.7),
]

E = 29_000_000.0
DECK_BRACE_SPACING_FT = 6.0
FB_BRACED = 24_000.0
FB_UNBRACED = 21_600.0

# --- the wrong turn -------------------------------------------------------
DEAD_PSF = {dead_psf!r}
LIVE_PSF = {live_psf!r}
SELECTION = {selection!r}          # "least_weight" | "first_row"
TIE = {tie!r}                      # "schedule_order" | "stiffest"
LU_SCREEN = {lu_screen!r}          # honour the Lb > Lu exclusion
FB_TIERS = {fb_tiers!r}            # honour the Lc/Lu allowable-stress tiers
SELF_WEIGHT = {self_weight!r}      # carry weight_plf in the dead load
LIVE_DEFL_LOAD = {live_defl_load!r}   # "live" | "total"
TOTAL_DEFL = {total_defl!r}        # apply the L/240 total-load check
# --------------------------------------------------------------------------


class SteelGaugePickEngine:

    def __init__(self, config=None):
        self._last = None

    def reset(self):
        self._last = None

    def configure(self, options=None):
        self._last = None

    @staticmethod
    def _positive(name, value):
        if isinstance(value, bool) or not isinstance(value, numbers.Real):
            raise ValidationError(name)
        if value <= 0:
            raise ValidationError(name)
        return float(value)

    def pick(self, length_ft, spacing_ft=2.0):
        length_ft = self._positive("length_ft", length_ft)
        spacing_ft = self._positive("spacing_ft", spacing_ft)
        L = length_ft * 12.0
        unbraced = min(DECK_BRACE_SPACING_FT, length_ft)
        w_live = LIVE_PSF * spacing_ft / 12.0
        w_super = DEAD_PSF * spacing_ft / 12.0

        best = None
        for index, (name, weight, Sx, Ix, Lc, Lu) in enumerate(SHAPES):
            if LU_SCREEN and unbraced > Lu:
                continue
            if FB_TIERS:
                Fb = FB_BRACED if unbraced <= Lc else FB_UNBRACED
            else:
                Fb = FB_BRACED

            w_total = w_super + w_live
            if SELF_WEIGHT:
                w_total += weight / 12.0

            if Sx * Fb < w_total * L * L / 8.0:
                continue
            w_defl = w_live if LIVE_DEFL_LOAD == "live" else w_total
            if 5.0 * w_defl * L ** 4 / (384.0 * E * Ix) > L / 360.0:
                continue
            if TOTAL_DEFL:
                if 5.0 * w_total * L ** 4 / (384.0 * E * Ix) > L / 240.0:
                    continue

            if SELECTION == "first_row":
                self._last = name
                return (name, round(Sx, 3), round(Ix, 2))
            if TIE == "stiffest":
                key = (weight, -Ix, index)
            else:
                key = (weight, 0.0, index)
            if best is None or key < best[0]:
                best = (key, name, Sx, Ix)

        if best is None:
            raise NotFoundError("nothing acceptable")
        _, name, Sx, Ix = best
        self._last = name
        return (name, round(Sx, 3), round(Ix, 2))
'''

CORRECT = dict(dead_psf=22.0, live_psf=50.0, selection="least_weight",
               tie="schedule_order", lu_screen=True, fb_tiers=True,
               self_weight=True, live_defl_load="live", total_defl=True)


def variant(**overrides):
    options = dict(CORRECT)
    options.update(overrides)
    return TEMPLATE.format(**options)


VARIANTS = [
    ("B", "first acceptable row of the shipped schedule",
     variant(selection="first_row")),
    ("B", "26.0 plf tie broken toward the stiffer member",
     variant(tie="stiffest")),
    ("H", "self-weight left out of the dead load",
     variant(self_weight=False)),
    ("H", "L/360 applied to the total load instead of the live load",
     variant(live_defl_load="total")),
    ("H", "L/240 total-load deflection check dropped",
     variant(total_defl=False)),
    ("H", "compute-once-then-scan: one load, one L/360, no L/240, no self-weight",
     variant(self_weight=False, live_defl_load="total", total_defl=False)),
    ("C", "flat SIGMA = 24,000 psi for every shape, no bracing screen",
     variant(lu_screen=False, fb_tiers=False)),
    ("C", "Lb > Lu exclusion ignored (stress tiers kept)",
     variant(lu_screen=False)),
    ("C", "allowable stress tiers ignored (exclusion kept)",
     variant(fb_tiers=False)),
    ("I", "the retired Revision A spreadsheet, fitted to the whole picks log",
     variant(dead_psf=10.0, selection="first_row", lu_screen=False,
             fb_tiers=False, self_weight=False, live_defl_load="total",
             total_defl=False)),
    ("I", "Revision A loads kept, everything else brought up to Revision B",
     variant(dead_psf=10.0)),
]

#: Reward has to stay continuous: a partly-correct implementation must score
#: partly. These are cumulative, each one solving one more crux than the last,
#: and every one of them is still wrong and must still fail.
LADDER = [
    ("nothing recovered - the retired spreadsheet verbatim",
     variant(dead_psf=10.0, selection="first_row", lu_screen=False,
             fb_tiers=False, self_weight=False, live_defl_load="total",
             total_defl=False)),
    ("B only - least weight, retired load model, flat allowable stress",
     variant(selection="least_weight", lu_screen=False, fb_tiers=False,
             self_weight=False, live_defl_load="total", total_defl=False)),
    ("B + H - loads and limit states right, bracing rule missed",
     variant(lu_screen=False, fb_tiers=False)),
    ("B + C - bracing rule right, retired load model kept",
     variant(self_weight=False, live_defl_load="total", total_defl=False)),
    ("B + H + C - everything but the weight tie-break",
     variant(tie="stiffest")),
]


# --------------------------------------------------------------------------

def run_tests(source, work):
    """(passed, failed) for the behaviour suite run against ``source``."""
    package = work / "engine"
    if package.exists():
        shutil.rmtree(package)
    shutil.copytree(REFERENCE, package,
                    ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
    (package / "engine.py").write_text(source, encoding="utf-8")

    environment = dict(os.environ)
    environment["ENGINE_DIR"] = str(package)
    environment["PYTHONDONTWRITEBYTECODE"] = "1"
    result = subprocess.run(
        [sys.executable, "-m", "pytest", str(TESTS), "-q", "--tb=no",
         "-p", "no:cacheprovider"],
        cwd=str(TASK), env=environment, capture_output=True, text=True,
        timeout=600)
    text = result.stdout

    def count(word):
        match = re.search(r"(\d+) %s" % word, text)
        return int(match.group(1)) if match else 0

    return count("passed"), count("failed") + count("error")


def load_engine(source, work, tag):
    """Import ``source`` as a throwaway module and return its engine class."""
    path = work / ("variant_%s.py" % tag)
    path.write_text(source, encoding="utf-8")
    import importlib.util
    spec = importlib.util.spec_from_file_location("variant_%s" % tag, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def picks_reproduced(module):
    """(rev A reproduced, rev A total, rev B reproduced, rev B total)."""
    if not PICKS.exists():
        return None
    counts = {"A": [0, 0], "B": [0, 0]}
    engine = module.SteelGaugePickEngine()
    with PICKS.open(newline="", encoding="utf-8") as handle:
        for row in csv.DictReader(handle):
            revision = row["std_rev"]
            if revision not in counts:
                continue
            counts[revision][1] += 1
            try:
                got = engine.pick(float(row["span_ft"]),
                                  float(row["spacing_ft"]))[0]
            except Exception:
                got = None
            if got == row["designation"]:
                counts[revision][0] += 1
    return counts["A"] + counts["B"]


def main():
    if not REFERENCE.exists():
        print("no reference engine at %s" % REFERENCE)
        return 1

    work = pathlib.Path(tempfile.mkdtemp(prefix="crux-"))
    try:
        reference_source = (REFERENCE / "engine.py").read_text(encoding="utf-8")
        passed, failed = run_tests(reference_source, work)
        if failed or not passed:
            print("BASELINE BROKEN: the reference engine scores %d/%d. "
                  "Nothing below would mean anything." % (passed, passed + failed))
            return 1
        passed_reference, total_reference = passed, passed + failed
        print("baseline: reference engine passes %d/%d test cases"
              % (passed_reference, total_reference))

        reference_module = load_engine(reference_source, work, "reference")
        counts = picks_reproduced(reference_module)
        if counts:
            print("          reproduces %d/%d std_rev=A picks and %d/%d "
                  "std_rev=B picks" % tuple(counts))
        print()

        survivors = []
        for index, (letter, label, source) in enumerate(VARIANTS):
            passed, failed = run_tests(source, work)
            total = passed + failed
            module = load_engine(source, work, str(index))
            counts = picks_reproduced(module)
            note = ""
            if counts:
                note = "   picks A %d/%d, B %d/%d" % tuple(counts)
            status = "caught " if failed else "SURVIVOR"
            print("%s  crux %s  %-62s %3d/%-3d passed%s"
                  % (status, letter, label, passed, total, note))
            if not failed:
                survivors.append((letter, label))

        print()
        print("partial credit ladder (each rung is still wrong and must still "
              "fail):")
        for label, source in LADDER:
            passed, failed = run_tests(source, work)
            total = passed + failed
            status = "caught " if failed else "SURVIVOR"
            print("%s  %-60s %3d/%-3d = %.3f"
                  % (status, label, passed, total,
                     passed / total if total else 0.0))
            if not failed:
                survivors.append(("ladder", label))
        print("         %-60s %3d/%-3d = %.3f"
              % ("the reference implementation, for scale", passed_reference,
                 total_reference,
                 passed_reference / total_reference if total_reference else 0.0))

        print()
        if survivors:
            print("SURVIVORS - the suite does not depend on these decisions:")
            for letter, label in survivors:
                print("  crux %s  %s" % (letter, label))
            return 1

        print("every wrong-default variant is caught by tests/test_outputs.py.")
        return 0
    finally:
        shutil.rmtree(work, ignore_errors=True)


if __name__ == "__main__":
    sys.exit(main())
